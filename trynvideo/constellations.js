function shuffled(items) {
  const result = [...items];
  for (let i = result.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

function drawConstellation([, , lines]) {
  const radians = Math.PI / 180;
  const points = lines.flat();
  const ra = points[0][0];
  const dec = points.reduce((sum, p) => sum + p[1], 0) / points.length * radians;
  const project = ([lon, lat]) => {
    const d = (lon - ra) * radians;
    const p = lat * radians;
    return [-Math.cos(p) * Math.sin(d), Math.sin(dec) * Math.cos(p) * Math.cos(d) - Math.cos(dec) * Math.sin(p)];
  };
  const projected = lines.map((line) => line.map(project));
  const xs = projected.flat().map(([x]) => x);
  const ys = projected.flat().map(([, y]) => y);
  const left = Math.min(...xs), right = Math.max(...xs);
  const top = Math.min(...ys), bottom = Math.max(...ys);
  const scale = Math.min(272 / (right - left), 140 / (bottom - top));
  const fit = ([x, y]) => [160 + (x - (left + right) / 2) * scale, 90 + (y - (top + bottom) / 2) * scale];
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 320 180");
  svg.setAttribute("class", "constellation-art");
  svg.setAttribute("aria-hidden", "true");
  const add = (tag, attrs) => {
    const node = document.createElementNS(svg.namespaceURI, tag);
    for (const [key, value] of Object.entries(attrs)) node.setAttribute(key, value);
    svg.append(node);
  };
  const stars = new Map();
  for (const line of projected) {
    const fitted = line.map(fit);
    add("polyline", { points: fitted.map((point) => point.join(",")).join(" ") });
    for (const point of fitted) stars.set(point.join(","), point);
  }
  for (const [cx, cy] of stars.values()) add("circle", { cx, cy, r: 3 });
  return svg;
}
